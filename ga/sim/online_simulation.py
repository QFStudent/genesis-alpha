def update_model_matrices(
    cfg: Config,
    model_obj: dict,
    y: pd.DataFrame,
    upload_path: str,
    date_format: str,
    scale: pd.DataFrame,
    sym: str,
):
    """
    Update estimation and make overnight return prediction

    Note: since in backtesting we want to simulate estimation without cur_date data
    to make overnight return prediction, we need to use date_format one day later than y.
    """
    date = str2date(date_format)
    upload_path = os.path.join(upload_path, str(date.year), str(date.month).zfill(2))
    Path(upload_path).mkdir(parents=True, exist_ok=True)

    solver = model_obj.fit_train(y)
    M = model_obj.sys.M.todense()
    N = model_obj.sys.N.todense()
    Q = model_obj.sys.Q.todense()
    U = model_obj.sys.U
    coef = model_obj.C
    z0 = model_obj.zhat0

    pd.DataFrame(coef["C1"]).to_csv(os.path.join(upload_path, f"{date_format}_coef.csv"))
    pd.DataFrame(z0).to_csv(os.path.join(upload_path, f"{date_format}_z0.csv"))
    pd.DataFrame(M).to_csv(os.path.join(upload_path, f"{date_format}_M.csv"))
    pd.DataFrame(N).to_csv(os.path.join(upload_path, f"{date_format}_N.csv"))
    pd.DataFrame(Q).to_csv(os.path.join(upload_path, f"{date_format}_Q.csv"))
    pd.DataFrame(U).to_csv(os.path.join(upload_path, f"{date_format}_U.csv"))
    scale.to_csv(os.path.join(upload_path, f"{date_format}_scale.csv"))


def update_pre_pred(
    cfg: Config,
    model_obj: dict,
    train_data: pd.DataFrame,
    test_data: pd.DataFrame,
    upload_path: str,
    date_format: str,
    scale: pd.DataFrame,
    sym: str,
):
    """Update previous day prediction in order to run model selection with new data"""
    date = str2date(date_format)
    _logger.info(f"Running yesterday prediction using model matrices of {str(date)}.")
    upload_path = os.path.join(upload_path, str(date.year), str(date.month).zfill(2))

    preds = model_obj.run_epoch(train_data, test_data)
    preds = pd.Series(preds.ravel(), index=test_data.index)
    final_preds = preds * scale.loc[sym, "std"]

    Path(upload_path).mkdir(parents=True, exist_ok=True)
    pd.DataFrame(final_preds).to_csv(os.path.join(upload_path, f"{date_format}_preds.csv"))
    # prediction date format is shifted since this will be the prediction we make at previous date
    pd.DataFrame(preds).to_csv(os.path.join(upload_path, f"{date_format}_scaled_preds.csv"))
    test_data.to_csv(os.path.join(upload_path, f"{date_format}_test_data.csv"))


