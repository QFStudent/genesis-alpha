    def fill_missing(self, minute_price: pd.DataFrame):
        if minute_price.isna().sum(axis=1).any():
            _logger.info("Minute price data contains Nans and ffill missing.")
            minute_price, missing_mask = ProcessSecondBar.fill_missing(minute_price)
        return minute_price

    def subsample_data(self, minute_price: pd.DataFrame):
        minute_rets = np.log(minute_price).diff(axis=0)
        minute_rets.iloc[0, :] = 0

        if self.system == "SISO":
            sub_dict = {}
            for sym in self.universe:
                sub_df = resample_bars(self.est_cfg, minute_rets[sym])
                sub_dict[sym] = sub_df["WEIGHTED"]
            sub_df = pd.DataFrame.from_dict(sub_dict, orient="columns")
            return sub_df
        else:
            raise NotImplementedError

    def one_hp_update(
        self,
        hp: dict,
        sym: str,
        pre_scale: pd.DataFrame,
        scale: pd.DataFrame,
        pre_train_data: pd.DataFrame,
        pre_test_data: pd.DataFrame,
        train_data: pd.DataFrame,
        ic_dates: List,
        metric_obj: object,
    ):
        model_obj = make_model_object(self.est_cfg, hp)
        upload_path = BackTesting.add_hp_2_prediction_path(hp, self.predPathDict[sym])
        update_model_matrices(
            self.est_cfg, model_obj, train_data, upload_path, self.preDateFormat[sym], scale, sym
        )
        update_pre_pred(
            self.est_cfg,
            model_obj,
            pre_train_data,
            pre_test_data,
            upload_path,
            self.preDateFormat[sym],
            pre_scale,
            sym,
        )
        load_hist_preds_rets(upload_path, ic_dates, metric_obj)

    def one_day_update(self, df: pd.DataFrame, sym: str):
        if self.system == "SISO":
            dates = pd.unique(df.index.date)
        else:
            raise NotImplementedError

        assert dates[-1] == self.preDateDict[sym], "last date doesn't match preDate"

        hps = extract_hp(self.est_cfg.hp)
        train_size = self.est_cfg.cv_cfg["kwargs"]["train_size"]
        metric_obj = init_instance_by_config(self.est_cfg.metric_cfg)
        if len(dates) < train_size:
            raise ValueError("Total dates is shorter than window size, the result will be inaccurate.")

        pre_train_dates = dates[:-1]
        pre_test_dates = dates[-1]
        pre_train_data, pre_test_data = (
            df.loc[str(pre_train_dates[0]) : str(pre_train_dates[-1])].copy(),
            df.loc[str(pre_test_dates)].copy(),
        )
        preprocess_obj = init_instance_by_config(self.est_cfg.cv_preprocess_cfg)
        pre_train_data, pre_test_data, pre_scale = preprocess_obj.fit(pre_train_data, pre_test_data)

        # prepare data for training including previous day
        train_dates = dates
        train_data = df.loc[str(train_dates[0]) : str(train_dates[-1])].copy()
        train_data, test_data, scale = preprocess_obj.fit(train_data, None)

        if self.njobs == 1:
            for hp in hps:
                self.one_hp_update(
                    hp,
                    sym,
                    pre_scale,
                    scale,
                    pre_train_data,
                    pre_test_data,
                    train_data,
                    dates[(train_size - 1):],
                    metric_obj,
                )
        else:
            Parallel(n_jobs=self.njobs)(
                delayed(self.one_hp_update)(
                    hp,
                    sym,
                    pre_scale,
                    scale,
                    pre_train_data,
                    pre_test_data,
                    train_data,
                    dates[(train_size - 1):],
                    metric_obj,
                )
                for hp in hps
            )

        one_day_select(
            self.preDateFormat[sym],
            self.pre2DateFormat[sym],
            hps,
            self.predPathDict[sym],
            self.matPathDict[sym],
        )

    def run(self):
        minute_price, adj_factor_df = self.append()
        minute_price = self.fill_missing(minute_price)
        sub_df = self.subsample_data(minute_price)

        for sym in self.universe:
            if self.system == "SISO":
                df = sub_df[[sym]]
            else:
                raise NotImplementedError
            self.one_day_update(df, sym)


