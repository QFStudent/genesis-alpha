def extract_opt_hp_path(hps: List, prediction_path: str, pre_date: str) -> dict:
    ic_grid = {}
    preDate = str2date(pre_date)
    for hp in hps:
        path = BackTesting.add_hp_2_prediction_path(hp, prediction_path)
        upload_path = os.path.join(path, str(preDate.year), str(preDate.month).zfill(2))
        ic_df = pd.read_csv(os.path.join(upload_path, f"{pre_date}_ic.csv"), index_col=0)
        ic_grid[tuple(hp.values())] = ic_df.squeeze()

    opt_hp = max(ic_grid, key=ic_grid.get)
    opt_hp_dict = dict(zip(hp.keys(), opt_hp))
    opt_hp_path_tmp = BackTesting.add_hp_2_prediction_path(opt_hp_dict, prediction_path)
    return opt_hp_path_tmp


