    def load_cfg(self):
        _logger.info("Load data config.")
        _logger.info("Load estimation config.")
        self.data_cfg = load_data_config(self.data_config)
        self.est_cfg = load_est_config(self.est_config)

    def load_historical_data(self, sym: str):
        path_ = os.path.join(
            self.data_cfg.storage,
            sym,
            self.pre2DateFormat[sym],
            f"{sym}_{self.pre2DateFormat[sym]}_adjusted_price.csv",
        )
        try:
            historical_df = pd.read_csv(path_, index_col=0)
        except Exception:
            raise ValueError(
                f"adjusted price hasn't been generated for {self.pre2DateFormat[sym]} yet."
            )
        historical_df.index = pd.to_datetime(historical_df.index)
        return historical_df

    def load_preDate_df(self, sym: str):
        df = extract_1_instrument_cc_data78(
            sym,
            self.data_cfg.prefix,
            str(self.preDateDict[sym]),
            self.data_cfg.file_name,
            self.data_cfg.field,
            self.data_cfg.timezone,
        )
        df = add_df_columns(df)
        return df

    def extract_front(self, sym: str):
        holidays = combine_holidays(
            load_holidays(self.data_cfg.holiday),
            load_holidays(sym),
        )
        roll_dates = extract_roll_dates(
            self.data_cfg.startdate,
            self.data_cfg.enddate,
            self.data_cfg.lookback,
            sym,
            holidays,
        )
        if self.data_cfg.field == "rth_fx":
            front_contract, second_contract = load_front_contract(sym, self.pre2DateDict[sym])
        else:
            front_map = front_contract_map(
                sym,
                self.data_cfg.startdate,
                self.data_cfg.enddate,
                roll_dates,
            )
            front_contract = front_map.loc[str(self.pre2DateDict[sym]), "FrontContract"]
            second_contract = front_map.loc[str(self.pre2DateDict[sym]), "SecondContract"]
        return front_contract, second_contract

    def extend_subsampled_bars(self, historical_df, front, preDate_df):
        front_df = preDate_df.loc[
            preDate_df["SYMBOL"] == front,
            [
                "LAST_BID",
                "LAST_BID_SIZE",
                "LAST_ASK",
                "LAST_ASK_SIZE",
                "LAST",
                "VOLUME",
                "VWAP",
                "ROOT",
                "EXP",
                "HS",
                "WEIGHTED",
                "MID",
            ],
        ]
        subsampled_bars = subsample_all_bar(front_df, self.data_cfg.freq)
        extended_df = pd.concat([historical_df, subsampled_bars], axis=0)
        return extended_df

    def extend_ratio_df(self, sym: str, front_c: str, sec_c: str, preDate_df: pd.DataFrame):
        ratio_path = os.path.join(
            self.data_cfg.storage,
            sym,
            self.pre2DateFormat[sym],
            f"{sym}_{self.pre2DateFormat[sym]}_roll_ratio.csv",
        )
        ratio_df = pd.read_csv(ratio_path, index_col=0)

        if self.data_cfg.field == 'rth_fx':
            ratio_df.columns = ["FrontContract", "Ratio"]

        # extend ratio and cum ratio
        if front_c == sec_c:
            ratio = 1
        else:
            _logger.info('There is roll adjustment yesterday.')
            ratio = get_roll_ratio(sym, preDate_df, front_c, sec_c, self.data_cfg.field)

        ratio_tmp = pd.DataFrame(
            data=[[front_c, ratio]],
            columns=["FrontContract", "Ratio"],
            index=[str(self.preDateDict[sym])],
        )
        extended_ratio = pd.concat([ratio_df, ratio_tmp], axis=0)
        extended_cum_ratio = extended_ratio.assign(
            Ratio=extended_ratio["Ratio"].iloc[::-1].cumprod().iloc[::-1]
        )
        return extended_ratio, extended_cum_ratio

    def adjust_price(self, extended_df: pd.DataFrame, ratio: float, historical_df: pd.DataFrame):
        price_cols = [
            "LAST",
            "MID",
            "WEIGHTED",
            "HIGH",
            "LOW",
            "OPEN",
            "VWAP",
            "VWAP1",
            "LAST_BID",
            "LAST_ASK",
        ]
        extended_df.loc[historical_df.index, price_cols] = (
            extended_df.loc[historical_df.index, price_cols] * ratio
        )
        return extended_df

    def save_new_data(
        self,
        new_bars: pd.DataFrame,
        new_ratio: pd.DataFrame,
        new_cum_ratio: pd.DataFrame,
        sym: str,
    ):
        _logger.info(f'Saving adjusted price of {sym} for {self.preDateFormat[sym]}.')
        new_bars.to_csv(self.adjustedPriceDict[sym])
        new_ratio.to_csv(self.ratioPathDict[sym])
        new_cum_ratio.to_csv(self.cumRatioDict[sym])

    def append(self):
        """Append daily data at date to the historical data and save the appended data"""
        extended_frame = []
        dfs = []
        adj_factor = []
        for sym in tqdm(self.universe):
            historical_df = self.load_historical_data(sym)
            front_contract, second_contract = self.extract_front(sym)
            preDate_df = self.load_preDate_df(sym)
            new_bars = self.extend_subsampled_bars(historical_df, front_contract, preDate_df)
            new_ratio, new_cum_ratio = self.extend_ratio_df(
                sym, front_contract, second_contract, preDate_df
            )
            new_bars = self.adjust_price(
                new_bars,
                new_ratio.loc[str(self.preDateDict[sym]), "Ratio"],
                historical_df,
            )
            self.save_new_data(new_bars, new_ratio, new_cum_ratio, sym)
            dfs.append(new_bars['WEIGHTED'])
            adj_factor.append(new_ratio["Ratio"])

        minute_price = pd.concat(dfs, axis=1).sort_index()
        adj_factor_df = pd.concat(adj_factor, axis=1)
        minute_price.columns = self.universe
        adj_factor_df.columns = self.universe
        minute_price.index = pd.to_datetime(minute_price.index)
        adj_factor_df = append_adj_factor(adj_factor_df, str(self.cur_date))
        return minute_price, adj_factor_df

